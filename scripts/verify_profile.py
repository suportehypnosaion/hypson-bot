"""
verify_profile.py — pre-deploy check for BROWSER_PROFILE_DIR.

Run this BEFORE every deploy (see DEPLOYMENT.md, "Verify the profile before
deploying"). It never launches a browser — it only reads Local State and
copies the cookie sqlite files — so it's safe to run against the profile
the live service is using.

For each Chrome sub-profile in BROWSER_PROFILE_DIR it prints:
  - the sub-profile dir + display name + signed-in user_name
  - whether it has Google auth cookies (SID/HSID/...)
And once, for the whole profile dir:
  - whether Local State's os_crypt.encrypted_key is present. If it is, this
    profile was encrypted with Windows DPAPI or macOS Keychain and CANNOT be
    decrypted on a Linux server/container, no matter what Chrome flags are
    passed at runtime — it must be regenerated by running
    `python -m scripts.setup_profile` ON A LINUX MACHINE.

Exit code is 0 only when a sub-profile signed in as SUPORTE_EMAIL, with
Google auth cookies present, in a Linux-made profile dir, is found.
"""

import sys

sys.path.insert(0, ".")

from bot import config, profile_utils


def main() -> int:
    user_data_dir = config.BROWSER_PROFILE_DIR
    print(f"Inspecting {user_data_dir}")
    print(f"SUPORTE_EMAIL = {config.SUPORTE_EMAIL!r}\n")

    profiles = profile_utils.list_profiles(user_data_dir)
    if not profiles:
        print(
            "Could not read Local State — is BROWSER_PROFILE_DIR correct, "
            "and has `python -m scripts.setup_profile` ever been run?"
        )
        return 1

    made_on_windows_or_mac = profile_utils.has_os_crypt_encrypted_key(user_data_dir)
    if made_on_windows_or_mac:
        print(
            "os_crypt.encrypted_key: PRESENT — this profile was created on "
            "Windows or macOS. It CANNOT be decrypted on a Linux server, "
            "regardless of Chrome flags.\n"
        )
    else:
        print("os_crypt.encrypted_key: absent — OK to decrypt on Linux.\n")

    match_dir = profile_utils.find_profile_for_user(user_data_dir, config.SUPORTE_EMAIL)
    found_good = False
    for profile_dir, info in profiles.items():
        user_name = info.get("user_name") or "(none)"
        name = info.get("name") or profile_dir
        has_cookies = profile_utils.has_google_auth_cookies(user_data_dir, profile_dir)
        marker = " <-- SUPORTE_EMAIL" if profile_dir == match_dir else ""
        print(
            f"  {profile_dir!r:16} name={name!r:20} user_name={user_name!r:30} "
            f"google_auth_cookies={has_cookies}{marker}"
        )
        if profile_dir == match_dir and has_cookies and not made_on_windows_or_mac:
            found_good = True

    print()
    if found_good:
        print("OK — a Linux-made, signed-in profile was found for SUPORTE_EMAIL.")
        return 0

    if not match_dir:
        print(f"FAILED — no sub-profile is signed in as {config.SUPORTE_EMAIL!r}.")
    elif made_on_windows_or_mac:
        print("FAILED — the matching profile exists but was made on Windows/macOS.")
    else:
        print("FAILED — the matching profile has no Google auth cookies.")
    print(
        "Run `python -m scripts.setup_profile` ON A LINUX MACHINE and redeploy."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
